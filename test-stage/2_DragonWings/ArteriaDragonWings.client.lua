-- ArteriaDragonWings.client.lua — LocalScript in StarterPlayer > StarterPlayerScripts.
-- Animates Dragonkin_Wings_02 on every visible character: drives the wing Motor6D.Transform values and
-- rebuilds the membranes each frame from the bone positions (two WedgeParts per triangle).
-- Client-only cosmetic: no RemoteEvents, no server state, nothing saved.
--
-- Control from your flight script (server or client) with character attributes:
--   character:SetAttribute("Flying", true)          -- flight cycle (power stroke + fold recovery)
--   character:SetAttribute("WingState", "Glide")    -- optional override: Folded | Idle | Glide | Flight
--   character:SetAttribute("WingFlapRate", 1.3)     -- optional stroke speed multiplier (1 = 1.6 s)
-- With no attributes the wings stay folded on the ground and glide while falling.
-- Generated by the Arteria Dragon Wings page — regenerate instead of hand-editing the rig tables.
local Players = game:GetService("Players")
local RunService = game:GetService("RunService")
local Workspace = game:GetService("Workspace")

local ACCESSORY_NAME = "Dragonkin_Wings_02"
local CONFIG = {
	FlyingAttribute = "Flying",
	StateAttribute = "WingState",
	FlapRateAttribute = "WingFlapRate",
	GlideWhenFalling = true,
	BlendSeconds = 0.6,
	MaxDistance = 140,
	MembraneColor = Color3.fromRGB(94, 26, 36),
	MembraneMaterial = Enum.Material.SmoothPlastic,
	MembraneThickness = 0.03,
}

-- Rig (right wing, Torso space, studs). Left wing is mirrored across X.
local REST = {
	S = Vector3.new(0.32, 0.55, 0.68),
	E = Vector3.new(1.17, 1.2, 0.86),
	W = Vector3.new(2.27, 1.5, 0.98),
	T = { Vector3.new(4.2, 1.05, 1.14), Vector3.new(3.65, -0.35, 1.1), Vector3.new(2.5, -1.25, 1) },
	B = Vector3.new(0.42, -0.6, 0.64),
}
local AX = {
	sweep = Vector3.new(0, -1, 0), lift = Vector3.new(0, 0, 1), twist = Vector3.new(0.7834, 0.599, 0.1659),
	elbow = Vector3.new(-0.0427, 0.1312, -0.9904), wrist = Vector3.new(-0.051, -0.204, 0.9776), spread = Vector3.new(-0.051, -0.204, 0.9776),
	cup = { Vector3.new(-0.2054, -0.9558, -0.2102), Vector3.new(-0.7853, -0.5965, -0.1655), Vector3.new(-0.9941, -0.0836, -0.0693) },
}
local RANGE = { elbow = 2.6, wrist = 1.4, spread = { 0, 0.7, 1.25 }, cup = { 0, 0.12, 0.24 } }
local GRID = { outerRings = 2, outerCols = 3, innerV = 2, sag = 0.22, innerSag = 0.18 }
local FLIGHT_PERIOD = 1.6
local TAU = math.pi * 2
local STATE_ORDER = { "Folded", "Idle", "Glide", "Flight" }

local function ext(p)
	p = p % 1
	if p < 0.28 then return 0.5 - 0.5 * math.cos(math.pi * p / 0.28) end
	if p < 0.6 then return 1 end
	if p < 0.9 then return 0.5 + 0.5 * math.cos(math.pi * (p - 0.6) / 0.3) end
	return 0
end

local function stateParams(state, t, phase)
	if state == "Folded" then
		return { sweep = 0.12, lift = -0.05, twist = 0, elbow = 1, wrist = 1, spread = 0 }
	elseif state == "Idle" then
		local b = math.sin(TAU * 0.22 * t)
		return { sweep = 0.18, lift = 0.02, twist = 0, elbow = 0.62 + 0.03 * b, wrist = 0.55, spread = 0.35 + 0.04 * b }
	elseif state == "Glide" then
		return { sweep = 0.12, lift = 0.14 + 0.03 * math.sin(TAU * 0.3 * t), twist = -0.05, elbow = 0.04, wrist = 0.02, spread = 1 }
	end
	local eE, eW, eF = ext(phase), ext(phase - 0.04), ext(phase - 0.08)
	return {
		sweep = 0.12 - 0.17 * math.cos(TAU * (phase - 0.2)),
		lift = 0.08 + 0.26 * math.cos(TAU * (phase - 0.15)),
		twist = -0.12 * math.sin(TAU * (phase - 0.35)),
		elbow = 0.62 * (1 - eE),
		wrist = 0.62 * (1 - eW),
		spread = 0.15 + 0.85 * eF,
	}
end

local function mAx(v, side) if side == "L" then return Vector3.new(v.X, -v.Y, -v.Z) end return v end
local function mPt(v, side) if side == "L" then return Vector3.new(-v.X, v.Y, v.Z) end return v end
local function rot(axis, a) return CFrame.fromAxisAngle(axis, a) end

-- Same forward kinematics as the preview. Returns Torso-space points and Motor6D transforms.
local function fk(p, side)
	local Ls = rot(mAx(AX.sweep, side), p.sweep) * rot(mAx(AX.lift, side), p.lift) * rot(mAx(AX.twist, side), p.twist)
	local Le = rot(mAx(AX.elbow, side), p.elbow * RANGE.elbow)
	local Lf = {}
	for i = 1, 3 do
		Lf[i] = rot(mAx(AX.wrist, side), p.wrist * RANGE.wrist)
			* rot(mAx(AX.spread, side), (1 - p.spread) * RANGE.spread[i])
			* rot(mAx(AX.cup[i], side), (1 - p.spread) * RANGE.cup[i])
	end
	local rS, rE, rW = mPt(REST.S, side), mPt(REST.E, side), mPt(REST.W, side)
	local Rh = Ls
	local Rf = Rh * Le
	local S = rS
	local E = S + Rh:VectorToWorldSpace(rE - rS)
	local W = E + Rf:VectorToWorldSpace(rW - rE)
	local T = {}
	for i = 1, 3 do
		T[i] = W + (Rf * Lf[i]):VectorToWorldSpace(mPt(REST.T[i], side) - rW)
	end
	return { S = S, E = E, W = W, T = T, B = mPt(REST.B, side) }, Ls, Le, Lf
end

local function lerp(a, b, t) return a + (b - a) * t end
local function safeUnit(v) local m = v.Magnitude if m < 1e-6 then return Vector3.zero end return v / m end

-- Membrane triangles (Torso space). Same grid as the preview: 34 triangles per wing.
local function membrane(P, out)
	local S, E, W, T, B = P.S, P.E, P.W, P.T, P.B
	local function outer(Ti, Tj)
		local R, F = GRID.outerRings, GRID.outerCols
		local span = (Tj - Ti).Magnitude
		local dir = safeUnit(W - (Ti + Tj) / 2)
		local rows = {}
		for k = 1, R do
			local r = k / R
			local row = {}
			for c = 0, F do
				local fr = c / F
				row[c] = lerp(lerp(W, Ti, r), lerp(W, Tj, r), fr) + dir * (GRID.sag * span * math.sin(math.pi * fr) * r ^ 3)
			end
			rows[k] = row
		end
		for c = 0, F - 1 do table.insert(out, { W, rows[1][c], rows[1][c + 1] }) end
		for k = 2, R do
			for c = 0, F - 1 do
				local a, b, cc, d = rows[k - 1][c], rows[k - 1][c + 1], rows[k][c], rows[k][c + 1]
				table.insert(out, { a, cc, d })
				table.insert(out, { a, d, b })
			end
		end
	end
	outer(T[1], T[2])
	outer(T[2], T[3])
	local T3 = T[3]
	local lse, lew = (E - S).Magnitude, (W - E).Magnitude
	local uE = lse / (lse + lew)
	local Vn = GRID.innerV
	local us = { 0, uE / 2, uE, uE + (1 - uE) / 2, 1 }
	local function A(u) if u <= uE then return lerp(S, E, u / uE) end return lerp(E, W, (u - uE) / (1 - uE)) end
	local function C(u)
		local base = lerp(B, T3, u)
		return base + safeUnit(A(u) - base) * (GRID.innerSag * (T3 - B).Magnitude * math.sin(math.pi * u))
	end
	local g = {}
	for i, u in us do
		local Au, Cu = A(u), C(u)
		g[i] = {}
		for j = 0, Vn do
			local v = j / Vn
			g[i][j] = Au * (1 - v) + Cu * v + lerp(S, B, v) * (1 - u) + lerp(W, T3, v) * u
				- (S * ((1 - u) * (1 - v)) + W * (u * (1 - v)) + B * ((1 - u) * v) + T3 * (u * v))
		end
	end
	for i = 1, #us - 1 do
		for j = 0, Vn - 1 do
			local a, b, c, d = g[i][j], g[i + 1][j], g[i][j + 1], g[i + 1][j + 1]
			table.insert(out, { a, b, d })
			table.insert(out, { a, d, c })
		end
	end
end

-- ---------- wedge triangles ----------
local folder = Instance.new("Folder")
folder.Name = "ArteriaWingMembranes"
folder.Parent = Workspace

local function newWedge()
	local w = Instance.new("WedgePart")
	w.Anchored = true
	w.CanCollide = false
	w.CanQuery = false
	w.CanTouch = false
	w.CastShadow = false
	w.Material = CONFIG.MembraneMaterial
	w.Color = CONFIG.MembraneColor
	w.TopSurface = Enum.SurfaceType.Smooth
	w.BottomSurface = Enum.SurfaceType.Smooth
	w.Size = Vector3.new(0.05, 0.05, 0.05)
	w.Parent = folder
	return w
end

local PARK = CFrame.new(0, -1e5, 0)
-- Fills two wedges for triangle a,b,c. Returns the CFrames (applied in one BulkMoveTo per frame).
local function triangle(a, b, c, w0, w1, cfs, i)
	local ab, ac, bc = b - a, c - a, c - b
	local abd, acd, bcd = ab:Dot(ab), ac:Dot(ac), bc:Dot(bc)
	if abd > acd and abd > bcd then
		c, a = a, c
	elseif acd > bcd and acd > abd then
		a, b = b, a
	end
	ab, ac, bc = b - a, c - a, c - b
	local cross = ac:Cross(ab)
	if cross.Magnitude < 1e-5 or bc.Magnitude < 1e-4 then
		cfs[i], cfs[i + 1] = PARK, PARK
		return
	end
	local right = cross.Unit
	local up = bc:Cross(right).Unit
	local back = bc.Unit
	local height = math.abs(ab:Dot(up))
	local t = CONFIG.MembraneThickness
	w0.Size = Vector3.new(t, math.max(height, 0.001), math.max(math.abs(ab:Dot(back)), 0.001))
	w1.Size = Vector3.new(t, math.max(height, 0.001), math.max(math.abs(ac:Dot(back)), 0.001))
	cfs[i] = CFrame.fromMatrix((a + b) / 2, right, up, back)
	cfs[i + 1] = CFrame.fromMatrix((a + c) / 2, -right, up, -back)
end

-- ---------- tracking ----------
local rigs = {} -- [Accessory] = record

local function destroyRig(acc)
	local r = rigs[acc]
	if not r then return end
	for _, w in r.wedges do w:Destroy() end
	for _, m in r.motors do
		if m.Parent then m.Transform = CFrame.identity end
	end
	rigs[acc] = nil
end

local function tryTrack(acc, character)
	if rigs[acc] or acc.Name ~= ACCESSORY_NAME or acc.Parent ~= character then return end
	local handle = acc:FindFirstChild("Handle")
	local bind = handle and handle:FindFirstChild("WingBind")
	if not bind then
		warn("[ArteriaDragonWings] " .. acc:GetFullName() .. " is missing Handle.WingBind; rebuild it with the setup script")
		return
	end
	local motors = {}
	for _, d in acc:GetDescendants() do
		if d:IsA("Motor6D") then motors[d.Name] = d end
	end
	for _, s in { "R", "L" } do
		for _, n in { "WingShoulder_", "WingElbow_", "WingFinger1_", "WingFinger2_", "WingFinger3_" } do
			if not motors[n .. s] then
				warn("[ArteriaDragonWings] missing Motor6D " .. n .. s .. " in " .. acc:GetFullName())
				return
			end
		end
	end
	local wedges = {}
	for i = 1, 2 * 34 * 2 do wedges[i] = newWedge() end
	rigs[acc] = {
		character = character, handle = handle, bind = bind.Value:Inverse(), motors = motors, wedges = wedges,
		weights = { Folded = 1, Idle = 0, Glide = 0, Flight = 0 }, phase = 0, cfs = {}, tris = {}, hidden = false,
	}
end

local function watchCharacter(character)
	for _, c in character:GetChildren() do
		if c:IsA("Accessory") then task.defer(tryTrack, c, character) end
	end
	character.ChildAdded:Connect(function(c)
		if c:IsA("Accessory") then task.defer(tryTrack, c, character) end
	end)
	character.ChildRemoved:Connect(destroyRig)
end
local function watchPlayer(player)
	if player.Character then watchCharacter(player.Character) end
	player.CharacterAdded:Connect(watchCharacter)
end
for _, p in Players:GetPlayers() do watchPlayer(p) end
Players.PlayerAdded:Connect(watchPlayer)

local function targetState(character)
	local override = character:GetAttribute(CONFIG.StateAttribute)
	if typeof(override) == "string" and table.find(STATE_ORDER, override) then return override end
	if character:GetAttribute(CONFIG.FlyingAttribute) == true then return "Flight" end
	local hum = character:FindFirstChildOfClass("Humanoid")
	if hum and CONFIG.GlideWhenFalling and hum:GetState() == Enum.HumanoidStateType.Freefall then return "Glide" end
	return "Folded"
end

local function hide(r)
	if r.hidden then return end
	r.hidden = true
	local cfs = table.create(#r.wedges, PARK)
	Workspace:BulkMoveTo(r.wedges, cfs, Enum.BulkMoveMode.FireCFrameChanged)
end

RunService.RenderStepped:Connect(function(dt)
	dt = math.min(dt, 0.1)
	local now = os.clock()
	local camera = Workspace.CurrentCamera
	for acc, r in rigs do
		if not acc.Parent or acc.Parent ~= r.character or not r.handle.Parent then
			destroyRig(acc)
			continue
		end
		local character = r.character
		local state = targetState(character)
		local rate = character:GetAttribute(CONFIG.FlapRateAttribute)
		rate = typeof(rate) == "number" and math.clamp(rate, 0.25, 3) or 1
		r.phase = (r.phase + dt * rate / FLIGHT_PERIOD) % 1

		local step = dt / CONFIG.BlendSeconds
		local total = 0
		local p = { sweep = 0, lift = 0, twist = 0, elbow = 0, wrist = 0, spread = 0 }
		for _, s in STATE_ORDER do
			local w = r.weights[s]
			w += math.clamp((s == state and 1 or 0) - w, -step, step)
			r.weights[s] = w
			if w > 1e-3 then
				local sp = stateParams(s, now, r.phase)
				for k, v in sp do p[k] += v * w end
				total += w
			end
		end
		for k, v in p do p[k] = v / total end

		local torsoCF = r.handle.CFrame * r.bind
		local far = camera and (torsoCF.Position - camera.CFrame.Position).Magnitude > CONFIG.MaxDistance
		table.clear(r.tris)
		for _, side in { "R", "L" } do
			local pts, Ls, Le, Lf = fk(p, side)
			r.motors["WingShoulder_" .. side].Transform = Ls
			r.motors["WingElbow_" .. side].Transform = Le
			for i = 1, 3 do r.motors["WingFinger" .. i .. "_" .. side].Transform = Lf[i] end
			if not far then membrane(pts, r.tris) end
		end
		if far then
			hide(r)
		else
			r.hidden = false
			for i, tri in r.tris do
				local a = torsoCF:PointToWorldSpace(tri[1])
				local b = torsoCF:PointToWorldSpace(tri[2])
				local c = torsoCF:PointToWorldSpace(tri[3])
				triangle(a, b, c, r.wedges[2 * i - 1], r.wedges[2 * i], r.cfs, 2 * i - 1)
			end
			Workspace:BulkMoveTo(r.wedges, r.cfs, Enum.BulkMoveMode.FireCFrameChanged)
		end
	end
end)
